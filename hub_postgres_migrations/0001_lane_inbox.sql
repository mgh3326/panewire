-- Hub lane inbox, the Postgres twin of openLaneInboxStore's SQLite schema.
-- Millisecond timestamps are BIGINT (SQLite INTEGER is 64-bit, Postgres
-- INTEGER is not). lane_inbox.id accepts explicit values so
-- `panewire hub migrate-sqlite` can keep item ids stable. lane_inbox_batches
-- gains seq in place of SQLite's implicit rowid: batches are sent in
-- creation order.
CREATE TABLE IF NOT EXISTS lane_inbox (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_key TEXT NOT NULL UNIQUE, lane TEXT NOT NULL,
 kind TEXT NOT NULL, class TEXT NOT NULL CHECK (class IN ('inbox','interrupt')),
 payload TEXT NOT NULL, created_at BIGINT NOT NULL, read_at BIGINT NOT NULL DEFAULT 0,
 acked_at BIGINT NOT NULL DEFAULT 0, due_at BIGINT NOT NULL DEFAULT 0,
 digest_at BIGINT NOT NULL DEFAULT 0, digest_batch TEXT NOT NULL DEFAULT '',
 escalation_batch TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS lane_inbox_unread ON lane_inbox(lane) WHERE class='inbox' AND read_at=0;
CREATE INDEX IF NOT EXISTS lane_inbox_due ON lane_inbox(due_at) WHERE class='inbox' AND read_at=0 AND escalation_batch='';
CREATE INDEX IF NOT EXISTS lane_inbox_digest ON lane_inbox(lane,digest_at) WHERE digest_at>0 AND digest_batch='';
CREATE TABLE IF NOT EXISTS lane_inbox_batches (
 seq BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,
 id TEXT PRIMARY KEY, lane TEXT NOT NULL, text TEXT NOT NULL, sent INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS lane_inbox_batch_quarantine (batch_id TEXT PRIMARY KEY, reason TEXT NOT NULL);
