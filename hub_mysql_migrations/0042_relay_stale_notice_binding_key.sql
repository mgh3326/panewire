-- hk 6994: the twin of Postgres migration 0045. The lane bindings of the
-- stale-replay notice are keyed by the receipt time, one binding per change of
-- the lane's job (hk 6976).
-- Rollback (MySQL): a hub binary from before this migration writes bindings
-- through insertIgnore, which is ON DUPLICATE KEY UPDATE here (hub_mysql.go), so
-- its writes do not fail. Under the key (worker_lane, first_ms) a write whose
-- (worker_lane, first_ms) is already held is a no-op, and any other write inserts
-- a row that staleReplayJobAt still resolves. Only Postgres and SQLite fail on
-- that binary: its binding write is refused (a warning, no binding), and stale
-- rows received in that window fall back to the lanes.json hint or the notice
-- lane. On MySQL that rollback loses no binding; on Postgres and SQLite it is a
-- known degradation, not a silent one.
-- applied-if: SELECT 1 - COUNT(*) FROM information_schema.statistics WHERE table_schema=DATABASE() AND table_name='relay_stale_notice_lanes' AND index_name='PRIMARY' AND column_name='job'
ALTER TABLE relay_stale_notice_lanes DROP PRIMARY KEY, ADD PRIMARY KEY (worker_lane, first_ms);
