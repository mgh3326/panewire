-- Durable acceptance, immutable node binding and transactional notifications:
-- the whole of spawn_operations after Postgres migrations 0004-0031 (phase 0
-- included: terminal_ms, replaced_from). The partial indexes of the Postgres
-- schema become plain indexes led by status; the hot sets are also kept in
-- spawn_queue and the outboxes.
-- applied-if: SELECT COUNT(*) FROM information_schema.tables WHERE table_schema=DATABASE() AND table_name='spawn_operations'
CREATE TABLE spawn_operations (
 request_id VARCHAR(255) NOT NULL,
 job VARCHAR(255) NOT NULL,
 owner VARCHAR(255) NOT NULL,
 fingerprint VARCHAR(255) NOT NULL,
 payload MEDIUMTEXT NOT NULL,
 status VARCHAR(64) NOT NULL,
 created_ms BIGINT NOT NULL,
 deadline_ms BIGINT NOT NULL,
 node_id VARCHAR(255) NULL,
 node_payload MEDIUMTEXT NOT NULL DEFAULT (''),
 result MEDIUMTEXT NOT NULL DEFAULT ('{}'),
 trace_recorded INT NOT NULL DEFAULT 0,
 last_run_ms BIGINT NOT NULL DEFAULT 0,
 attempt INT NOT NULL DEFAULT 1,
 placed_ms BIGINT NOT NULL DEFAULT 0,
 claimed_ms BIGINT NOT NULL DEFAULT 0,
 exclusions MEDIUMTEXT NOT NULL DEFAULT ('[]'),
 claimed_host VARCHAR(255) NOT NULL DEFAULT '',
 refresh_waits TEXT NOT NULL DEFAULT ('[]'),
 expires_ms BIGINT NOT NULL DEFAULT 0,
 conditions_met_ms BIGINT NOT NULL DEFAULT 0,
 condition_result TEXT NOT NULL DEFAULT (''),
 park_reason VARCHAR(1024) NOT NULL DEFAULT '',
 next_check_ms BIGINT NOT NULL DEFAULT 0,
 failed_attempts INT NOT NULL DEFAULT 0,
 claim_result TEXT NOT NULL DEFAULT (''),
 park_since_ms BIGINT NOT NULL DEFAULT 0,
 park_priority INT NOT NULL DEFAULT -1,
 park_notice_ms BIGINT NOT NULL DEFAULT 0,
 park_judged_reason VARCHAR(1024) NOT NULL DEFAULT '',
 park_priority_failures INT NOT NULL DEFAULT 0,
 placed_account_key VARCHAR(255) NOT NULL DEFAULT '',
 placed_attempt INT NOT NULL DEFAULT 0,
 task_fail_notice_ms BIGINT NOT NULL DEFAULT 0,
 task_fail_retry_ms BIGINT NOT NULL DEFAULT 0,
 terminal_ms BIGINT NOT NULL DEFAULT 0,
 replaced_from VARCHAR(255) NULL,
 PRIMARY KEY (request_id),
 UNIQUE KEY spawn_operations_node_id (node_id),
 KEY spawn_operations_queue (status, last_run_ms, created_ms, request_id),
 KEY spawn_operations_created (status, created_ms, request_id),
 KEY spawn_operations_parked_wake (status, next_check_ms, request_id),
 KEY spawn_operations_park_notice (status, park_since_ms, request_id),
 KEY spawn_operations_bound_unclaimed (claimed_ms, placed_ms),
 KEY spawn_operations_terminal (terminal_ms),
 KEY spawn_operations_job (job),
 KEY spawn_operations_replaced_from (replaced_from)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
